#!/bin/bash
# ===================================================
#  ゴルフ場 営業指示エージェント  起動スクリプト（Mac / Linux）
#  使い方：ターミナルで  ./start.sh  と入力してEnter
# ===================================================
set -e
cd "$(dirname "$0")"

echo "■ 必要なライブラリを確認しています…"
python3 -m pip install -q -r requirements.txt

echo "■ データベースを準備しています…"
python3 -m app.cli init

echo "■ 本日の営業指示を作成しています…"
python3 -m app.cli run || echo "（データがまだ無い場合は、画面から取り込んでください）"

echo ""
echo "======================================================"
echo "  ブラウザで次のアドレスを開いてください"
echo "      http://127.0.0.1:8000"
echo "  終了するときは、この画面で Ctrl + C を押してください"
echo "======================================================"
echo ""
python3 -m uvicorn app.main:app --host 127.0.0.1 --port 8000
