def render(message_key: str, channel: str, variables: dict) -> tuple[str, str]:
    """テンプレートに値を差し込んで、(件名, 本文) を返します。"""
    subject, body = TEMPLATES.get((message_key, channel), FALLBACK.get(channel, ("", "")))
    values = dict(variables)
    values.setdefault("course_name", "当ゴルフ場")
    values.setdefault("dates", "")
    values.setdefault("month", "")

    def fill(text: str) -> str:
        out = text
        for key, value in values.items():
            out = out.replace("{" + key + "}", str(value))
        return out

    return fill(subject), fill(body)


def sms_length_warning(body: str) -> str | None:
    """SMSが長すぎないかを確認します（全角70文字を超えると料金が上がります）。"""
    length = len(body.replace("（URL）", "https://exmpl.jp/xxxxx"))
    if length > 70:
        return f"SMSの目安70文字を超えています（現在{length}文字）。分割送信で料金が上がる可能性があります。"
    return None
